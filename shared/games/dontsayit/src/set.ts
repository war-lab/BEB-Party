// お題データのスキーマ。このファイルの型定義がスキーマの正本である（基本設計/09_DONTSAYITゲームモジュール.md）。
// 推論エンジンを使わないため、検証は文字列比較と枚数の計数だけで足りる。

/** 1枚のお題。正解（人物・もの・場所などセットの主題）と、それを説明するときに使えない語の組 */
export interface Card {
  id: string;
  /** 正解の名前。英字・空白・ハイフン・アポストロフィのみ */
  answer: string;
  /**
   * 正解の日本語名。説明者と監視役にだけ配る（09の日本語のお題補助）。
   *
   * 物や場所を知っていることと、英語名を見てそれを認識できることは別である。
   * `clothespin` を読んで洗濯ばさみだと分からない説明者は、英語力と無関係に沈黙する。
   * スキップは1ラウンド1回しかないため、この経路を塞ぐ手段が他にない。
   */
  ja: string;
  /**
   * 正解として受理する別名・略称。省略時は無しとして扱う。
   *
   * 説明者はこれらも言えない（09の言えない語の範囲）。
   * 回答として受理する語を説明者が言えると、正解そのものを言って成立させられる。
   *
   * 禁止語の5語とは別枠であり、レベルに関係なく常に全件を提示する。
   * レベルで提示数を変えると、レベル1〜2だけが「言ってよい別名」を持つことになる。
   */
  aliases?: string[];
  /**
   * 禁止語。常に5語を収録する。
   *
   * 正解に強く結びつく順に並べる。レベル1〜2の説明者には先頭3語だけを提示するため、
   * 並び順が難度を決める（09のレベル差の吸収）。
   *
   * 正解の構成語と複合語の構成要素は規則で既に禁止されているため、ここには書かない（検証1・検証10）。
   */
  taboo: string[];
}

/** 説明の仕方に条件を足すカード。案17 CHARADES+ を統合した要素であり、レベル5の説明者にだけ配る */
export interface ConstraintCard {
  id: string;
  ja: string;
  en: string;
}

export interface KeyExpression {
  en: string;
  ja: string;
}

/** お題セット1本。content/dontsayit/<id>.json の中身 */
export interface TabooSet {
  id: string;
  title: string;
  cards: Card[];
  constraints: ConstraintCard[];
  keyExpressions: KeyExpression[];
}

/**
 * 1枚に収録する禁止語の数。提示数はレベルで変えるが、収録数は固定する（09の検証3）。
 *
 * 5語から15語へ増やした。5語では共演者名・代表作名・素材・用途を同時に塞げず、
 * 1語で即答されるカードが多数あった（クロスレビュー観点B）。
 * 15語あると、有用な禁止語を捨てて別の禁止語を入れる取引が要らなくなる。
 */
export const TABOO_PER_CARD = 15;

/** 1枚に収録できる別名の上限。監視役が見て判定できる数に収める（09の言えない語の範囲） */
export const ALIASES_MAX = 3;

/**
 * 山札の下限枚数。
 *
 * 1ラウンドの最大消費枚数は5枚である。カードを送れる回数の上限が5回で、
 * 上限に達した時点でラウンドが終わるため、締切時に捨てる1枚が上乗せされることはない。
 * 対応人数の上限6人が全員説明者を務められるよう、6×5=30枚を下限とする（09の検証4）。
 */
export const MIN_CARDS = 30;
